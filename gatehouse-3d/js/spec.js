/** 便捷：檐带纵向区间（中央平段） */
export function eaveSpan(e) {
  return [e.yTop - e.h + 1, e.yTop];
}
/** 便捷：檐带对称横向区间 [cx-halfW, cx+halfW-1]（端点之和恒为 159） */
export function eaveRangeX(e) {
  return [e.cx - e.halfW, e.cx + e.halfW - 1];
}
